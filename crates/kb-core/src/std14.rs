/// Encodes text in WinAnsi (the encoding of the standard PDF fonts).
/// Characters it can't represent become '?'.
pub(crate) fn winansi(s: &str) -> Vec<u8> {
    s.chars()
        .map(|c| {
            let mut buf = [0u8; 4];
            let (enc, _, bad) = encoding_rs::WINDOWS_1252.encode(c.encode_utf8(&mut buf));
            if bad || enc.len() != 1 { b'?' } else { enc[0] }
        })
        .collect()
}

/// Width of a WinAnsi string in points.
pub(crate) fn text_width(bytes: &[u8], size: f32, bold: bool) -> f32 {
    let t = if bold { &HELVETICA_BOLD } else { &HELVETICA };
    bytes
        .iter()
        .map(|&b| if b >= 32 { t[(b - 32) as usize] as f32 } else { 0.0 })
        .sum::<f32>()
        * size
        / 1000.0
}

/// Greedy word wrap for a standard font.
pub(crate) fn wrap(text: &str, size: f32, bold: bool, max_width: f32) -> Vec<String> {
    let mut lines = vec![];
    for para in text.split('\n') {
        let mut line = String::new();
        for word in para.split(' ') {
            let candidate = if line.is_empty() { word.to_string() } else { format!("{line} {word}") };
            if !line.is_empty() && text_width(&winansi(&candidate), size, bold) > max_width {
                lines.push(std::mem::take(&mut line));
                line = word.to_string();
            } else {
                line = candidate;
            }
        }
        lines.push(line);
    }
    lines
}
